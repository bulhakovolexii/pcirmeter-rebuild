const cache = new Map<PaletteId, Uint8Array>()

/** Палітра як `Uint8Array` RGB (768 байтів: R, G, B для індексів 0…255). */
export function palette(id: PaletteId): Uint8Array {
  let rgb = cache.get(id)
  if (!rgb) {
    const hex = HEX[id]
    rgb = new Uint8Array(768)
    for (let i = 0; i < 768; i++) rgb[i] = parseInt(hex.slice(2 * i, 2 * i + 2), 16)
    cache.set(id, rgb)
  }
  return rgb
}
